/** Frameworks que servem páginas, na ordem de preferência para hospedar /onboarding num monorepo. */
const WEB_HOSTS: Framework[] = ["next", "nuxt", "sveltekit", "remix", "astro", "vite", "cra", "gatsby", "angular", "nest", "adonis", "express", "fastify", "koa", "hono", "elysia", "webpack"];

/** O app do monorepo que recebe a rota: o escolhido em --project ou o primeiro web app pela ordem de WEB_HOSTS. */
export function pickRouteHost(rootFramework: Framework, subprojects: Subproject[]): Subproject | undefined {
  if (WEB_HOSTS.includes(rootFramework)) return undefined; // a raiz já é o app
  const rank = (s: Subproject) => WEB_HOSTS.indexOf(s.framework);
  return subprojects.filter((s) => rank(s) >= 0).sort((a, b) => rank(a) - rank(b))[0];
}

function installHint(packageManager: string | undefined, sub: Subproject): string {
  switch (packageManager) {
    case "pnpm":
      return `pnpm add -D onboarding-kit --filter ${sub.name}`;
    case "yarn":
      return `yarn workspace ${sub.name} add -D onboarding-kit`;
    case "bun":
      return `cd ${sub.path} && bun add -d onboarding-kit`;
    default:
      return `npm install -D onboarding-kit -w ${sub.path}`;
  }
}

