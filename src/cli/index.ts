/** Adiciona o OnboardingModule ao app.module.ts quando dá para fazer isso com segurança. */
export function patchNestAppModule(source: string, file?: string): string | undefined {
  if (source.includes("OnboardingModule")) return source;
  const register = withFile("OnboardingModule.register()", file);
  const matches = source.match(/imports\s*:\s*\[/g);
  if (!matches || matches.length !== 1) return undefined;
  const withImport = source.replace(/imports\s*:\s*\[(\s*\])?/, (m, empty?: string) =>
    empty ? m.replace(/\[\s*\]$/, `[${register}]`) : `${m}${register}, `,
  );
  return `import { OnboardingModule } from "onboarding-kit/nest";\n${withImport}`;
}

/** Adiciona o plugin onboarding() ao vite.config quando dá para fazer isso com segurança. */
export function patchViteConfig(source: string, call = "onboarding()"): string | undefined {
  if (source.includes("onboarding-kit/vite")) return source;
  const cjs = !/^\s*import\s/m.test(source) && /require\(/.test(source);
  const importLine = cjs ? `const { onboarding } = require("onboarding-kit/vite");` : `import { onboarding } from "onboarding-kit/vite";`;
  const plugins = source.match(/plugins\s*:\s*\[/g);
  let patched: string | undefined;
  if (plugins?.length === 1) {
    patched = source.replace(/plugins\s*:\s*\[(\s*\])?/, (m, empty?: string) => (empty ? m.replace(/\[\s*\]$/, `[${call}]`) : `${m}${call}, `));
  } else if (!plugins && (source.match(/defineConfig\(\s*\{/g) ?? []).length === 1) {
    patched = source.replace(/defineConfig\(\s*\{/, (m) => `${m}\n  plugins: [${call}],`);
  }
  return patched && `${importLine}\n${patched}`;
}

function setupVite(root: string, framework: Framework, file?: string): string[] {
  const config = VITE_CONFIGS.find((f) => existsSync(join(root, f)));
  const call = withFile("onboarding()]", file).slice(0, -1);
  if (config) {
    const source = readFileSync(join(root, config), "utf8");
    const patched = patchViteConfig(source, call);
    if (patched === source) return [tr(`${c.dim("•")} ${config} já usa o plugin do onboarding-kit`, `${c.dim("•")} ${config} already uses the onboarding-kit plugin`)];
    if (patched) {
      writeFileSync(join(root, config), patched);
      return [tr(`${c.green("✓")} Adicionei ${c.bold("onboarding()")} aos plugins do ${config} (rota /onboarding no vite dev)`, `${c.green("✓")} Added ${c.bold("onboarding()")} to the ${config} plugins (/onboarding route in vite dev)`)];
    }
  }
  return [tr(`${c.yellow("!")} Não consegui editar o ${config ?? "vite.config"} sozinho. Adicione:`, `${c.yellow("!")} Couldn't edit ${config ?? "vite.config"} automatically. Add:`), "", c.dim(withFile(SNIPPETS[framework] ?? SNIPPETS.vite!, file))];
}

function createRouteFile(root: string, framework: Framework, file?: string): string[] {
  const route = ROUTE_FILES[framework]!;
  const source = withFile(route.source, file);
  const ext = existsSync(join(root, "tsconfig.json")) ? "ts" : "js";
  const rel = route.file(ext);
  if (existsSync(join(root, rel))) {
    return [tr(`${c.yellow("!")} ${rel} já existe. Para servir em /onboarding, use:`, `${c.yellow("!")} ${rel} already exists. To serve /onboarding, use:`), "", c.dim(framework === "cra" ? withFile(`app.all("/onboarding", require("onboarding-kit/node").createOnboardingHandler());`, file) : source)];
  }
  mkdirSync(dirname(join(root, rel)), { recursive: true });
  writeFileSync(join(root, rel), source);
  return [tr(tr(`${c.green("✓")} Criei ${c.bold(rel)} (rota /onboarding)`, `${c.green("✓")} Created ${c.bold(rel)} (/onboarding route)`), `${c.green("✓")} Created ${c.bold(rel)} (/onboarding route)`)];
}

/** Comando para rodar um script do package.json no gerenciador do projeto. */
export function runScript(packageManager: string | undefined, name: string): string {
  if (packageManager === "yarn" || packageManager === "pnpm") return `${packageManager} ${name}`;
  return `${packageManager === "bun" ? "bun" : "npm"} run ${name}`;
}

/** Script `onboarding` no package.json: abre a apresentação em localhost:4321 em qualquer projeto, com ou sem servidor web. */
export function addServeScript(root: string, packageManager?: string): string[] {
  const path = join(root, "package.json");
  if (!existsSync(path)) return [tr(`${c.dim("•")} Para ver a apresentação: ${c.bold("deno run -A npm:onboarding-kit serve")}`, `${c.dim("•")} To see the presentation: ${c.bold("deno run -A npm:onboarding-kit serve")}`)];
  const raw = readFileSync(path, "utf8");
  const pkg = JSON.parse(raw);
  const run = runScript(packageManager, "onboarding");
  if (pkg.scripts?.onboarding) return [tr(`${c.dim("•")} O script ${c.bold(run)} já existe no package.json`, `${c.dim("•")} The ${c.bold(run)} script already exists in package.json`)];
  pkg.scripts = { ...(pkg.scripts ?? {}), onboarding: "onboarding-kit serve" };
  const indent = /^(\s+)"/m.exec(raw)?.[1] ?? "  ";
  writeFileSync(path, JSON.stringify(pkg, null, indent) + (raw.endsWith("\n") ? "\n" : ""));
  return [tr(`${c.green("✓")} Adicionei o script ${c.bold(run)} (abre a apresentação em http://localhost:4321)`, `${c.green("✓")} Added the ${c.bold(run)} script (opens the presentation at http://localhost:4321)`)];
}

