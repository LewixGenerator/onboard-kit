/** Escapa o texto de um comando do GitHub Actions (::error ...::mensagem). */
const ghEscape = (value: string, prop = false) => {
  const out = value.replace(/%/g, "%25").replace(/\r/g, "%0D").replace(/\n/g, "%0A");
  return prop ? out.replace(/:/g, "%3A").replace(/,/g, "%2C") : out;
};

/** Anotações no PR (::error/::warning) e um resumo no job, quando roda no GitHub Actions. */
export function reportToCi(issues: Issue[], file: string): void {
  for (const issue of issues) {
    console.log(`::${issue.level} file=${ghEscape(file, true)},title=${ghEscape(`onboarding: ${issue.path || "(raiz)"}`, true)}::${ghEscape(issue.message)}`);
  }
  const summary = process.env.GITHUB_STEP_SUMMARY;
  if (!summary) return;
  const rows = issues.map((i) => `| ${i.level === "error" ? "❌" : "⚠️"} | \`${i.path || "(raiz)"}\` | ${i.message.replace(/\|/g, "\\|")} |`);
  appendFileSync(summary, `### onboarding-kit validate\n\n${rows.length ? `${tr("| | Campo | Problema |", "| | Field | Problem |")}\n|---|---|---|\n${rows.join("\n")}` : tr("✅ Nenhum problema.", "✅ No problems.")}\n\n`);
}

